"""Verify that generated docs carry the header and only cite real files and lines.

Citation format: ``src: path``, ``src: path:12`` or ``src: path:12-20``, paths relative to
the repository root. Exits 1 if any check fails.
"""

import argparse
import re
import sys
from pathlib import Path

HEADER = "<!-- Generated by the docs-sync agent. Do not edit by hand. -->"
CITATION = re.compile(r"src: ([A-Za-z0-9_./-]+?)(?::(\d+)(?:-(\d+))?)?(?=[)\];,\s]|$)")
NO_CITATION_NEEDED = {"README.md", "CHANGELOG.md"}


def _line_count(path: Path) -> int:
    return len(path.read_text(encoding="utf-8", errors="replace").splitlines())


def check_citation(root: Path, rel: str, start: str | None, end: str | None) -> str | None:
    """Return an error message, or None if the citation is valid."""
    target = (root / rel).resolve()
    if target != root and root not in target.parents:
        return f"{rel}: outside the repository"
    if (root / ".agent") in [target, *target.parents]:
        return f"{rel}: CI working files are not committed"
    if not target.exists():
        return f"{rel}: does not exist"
    if start is None:
        return None
    if not target.is_file():
        return f"{rel}: line given for a folder"
    first, last = int(start), int(end or start)
    if first < 1 or last < first:
        return f"{rel}:{start}-{end}: invalid range"
    if last > _line_count(target):
        return f"{rel}:{last}: beyond end of file"
    return None


def check_document(doc: Path, root: Path) -> list[str]:
    text = doc.read_text(encoding="utf-8")
    errors = []
    if not text.startswith(HEADER):
        errors.append("missing generated header on first line")
    citations = CITATION.findall(text)
    if not citations and doc.name not in NO_CITATION_NEEDED:
        errors.append("no citations")
    for rel, start, end in citations:
        error = check_citation(root, rel, start or None, end or None)
        if error:
            errors.append(f"bad citation {error}")
    return errors


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("docs_dir", type=Path, nargs="?", default=Path("docs/generated"))
    parser.add_argument("--root", type=Path, default=Path.cwd())
    args = parser.parse_args(argv)

    root = args.root.resolve()
    docs = sorted(args.docs_dir.rglob("*.md"))
    if not docs:
        print(f"No generated docs found in {args.docs_dir}", file=sys.stderr)
        return 1

    failed = False
    for doc in docs:
        for error in check_document(doc, root):
            failed = True
            print(f"{doc.relative_to(args.docs_dir).as_posix()}: {error}", file=sys.stderr)
    if not failed:
        print(f"{len(docs)} documents checked, all citations valid")
    return 1 if failed else 0


if __name__ == "__main__":
    sys.exit(main())
